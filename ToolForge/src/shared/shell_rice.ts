/**
 * Generates an optimized starship.toml configuration file
 */
export function generateStarshipToml(config: RiceConfig): string {
  const palette = PALETTES[config.preset];
  const char = config.enableNerdFonts ? config.promptChar : '>';

  let toml = `# Starship Prompt Configuration [${palette.name}]
# Generated by ToolForge Shell Rice Engine

add_newline = false
format = """
$directory\\
\${custom.git_branch}\\
$git_status\\
$nodejs\\
$python\\
$cmd_duration\\
$line_break\\
$character"""

[character]
success_symbol = "[\${char}](${palette.cyan} bold)"
error_symbol = "[\${char}](${palette.red} bold)"

[directory]
style = "${palette.yellow} bold"
truncation_length = 3
truncation_symbol = "…/"
read_only = " 󰌾"
`;

  if (config.showGitStatus) {
    toml += `
[git_branch]
symbol = " "
style = "${palette.magenta} bold"
format = "[$symbol$branch]($style) "

[git_status]
style = "${palette.red} bold"
format = "([$all_status$ahead_behind]($style) )"
conflicted = "󰞇 "
ahead = "⇡\${count}"
behind = "⇣\${count}"
diverged = "⇕⇡\${ahead_count}⇣\${behind_count}"
untracked = "?\${count}"
modified = "!\${count}"
staged = "+\${count}"
`;
  }

  if (config.showNodeVersion) {
    toml += `
[nodejs]
symbol = " "
style = "${palette.green} bold"
format = "via [$symbol($version )]($style)"
`;
  }

  if (config.showPythonVenv) {
    toml += `
[python]
symbol = " "
style = "${palette.blue} bold"
format = "via [$symbol(\${pyenv_prefix}(\${version} )(\\(\$virtualenv\\) ))]($style)"
`;
  }

  if (config.showExecutionTime) {
    toml += `
[cmd_duration]
min_time = 500
style = "${palette.cyan} italic"
format = "took [$duration]($style) "
`;
  }

  return toml.trim();
}

/**
 * Generates Windows Terminal color scheme JSON object
 */
export function generateWindowsTerminalScheme(preset: RicePreset): Record<string, string> {
  const p = PALETTES[preset];
  return {
    name: p.name,
    background: p.background,
    foreground: p.foreground,
    cursorColor: p.cyan,
    black: '#121212',
    red: p.red,
    green: p.green,
    yellow: p.yellow,
    blue: p.blue,
    purple: p.magenta,
    cyan: p.cyan,
    white: '#e0e0e0',
    brightBlack: '#555555',
    brightRed: p.red,
    brightGreen: p.green,
    brightYellow: p.yellow,
    brightBlue: p.blue,
    brightPurple: p.magenta,
    brightCyan: p.cyan,
    brightWhite: '#ffffff'
  };
}
